#!/usr/bin/env node
/**
 * The list of /api routes THIS BUNDLE CALLS, extracted from the source it is built from.
 *
 * Why generated and not hand-written: the app can already explain a 404 as "this server predates the
 * route" (lib/serverAge), but only AFTER the operator clicks and the request fails. On this machine
 * the running server lacks TEN routes the UI calls, so ten features are dark and each one is
 * discovered mid-task. To warn BEFORE the click, the page must know what it needs — and a
 * hand-maintained list of that would go stale the way every hand-maintained list in this repo has
 * (the consent kinds went stale twice).
 *
 * `--check` re-extracts and fails if the committed file disagrees, which is what makes it trustworthy
 * in `npm test`: a generated file nobody regenerates is just a stale hand-written one.
 *
 * Paths are stored TEMPLATED (/api/devices/camera/{index}/modes) because that is the shape
 * openapi.json publishes, and serverAge.routeKnown's `[^/]+` segment matcher accepts a literal
 * {index} as one segment — so the comparison needs no second path algebra.
 */
import fs from 'node:fs'
import path from 'node:path'
import { routeSites } from './lib/frontend-routes.mjs'

const SRC = path.resolve('src')
const OUT = path.join(SRC, 'lib', 'bundleRoutes.generated.ts')

/* Extraction is SHARED with the typo gate (scripts/lib/frontend-routes.mjs) so the two cannot
 * disagree about what this bundle calls. Here the raw literals are normalised into the shape
 * openapi.json publishes: `${expr}` becomes {p}, one path SEGMENT, which is what a server template
 * means too. A path this cannot judge is DROPPED rather than guessed — a ternary or a query inside
 * the literal, or a concatenated base — and the count printed below is the honest surface. */
const routes = new Set()
for (const raw of routeSites(SRC).keys()) {
  if (!raw.startsWith('/api/')) continue                    // /ws sockets are the gate's business, not openapi's
  /* A TRAILING SLASH IS MEANINGFUL and must survive: endpoints.ts lists '/api/auth/login/' and
   * '/api/auth/register/' as BASES that callers concatenate onto ('…/begin', '…/finish'). Stripping
   * the slash turned each into a route the server has never had, and the banner then accused a
   * healthy server of two missing features — measured in a browser before this fix. darkFeatures
   * satisfies a base from any route beneath it, exactly as the typo gate does. */
  const p = raw.split('?')[0].replace(/\$\{[^}]*\}/g, '{p}')
  if (/[$?\s]/.test(p)) continue                             // a mangled interpolation: refuse rather than guess
  routes.add(p)
}
const sorted = [...routes].sort()

const body = `/* GENERATED by scripts/gen-bundle-routes.mjs — do not edit by hand.
 * Every /api path this bundle asks for, templated the way openapi.json publishes them. Used to warn
 * that a route is missing from the running server BEFORE the operator clicks it (see lib/darkFeatures).
 * Regenerate: node scripts/gen-bundle-routes.mjs   ·   npm test fails when this file is stale.
 */
export const BUNDLE_ROUTES: readonly string[] = [
${sorted.map(p => `  '${p}',`).join('\n')}
]
`

if (process.argv.includes('--check')) {
  const have = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : ''
  if (have !== body) {
    console.error(`  FAIL  bundleRoutes.generated.ts is STALE — run: node scripts/gen-bundle-routes.mjs`)
    process.exit(1)
  }
  console.log(`  PASS  bundle route list current (${sorted.length} routes this UI calls)`)
} else {
  fs.writeFileSync(OUT, body)
  console.log(`  wrote ${path.relative(process.cwd(), OUT)} — ${sorted.length} routes this UI calls`)
}
